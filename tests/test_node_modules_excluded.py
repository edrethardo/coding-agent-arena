"""node_modules gehoert weder in den Build-Hash noch auf die Seite.

Ein Agent darf sich ein Testwerkzeug installieren; die 131k-Zeile hat jsdom geholt
(27 MB, 1830 Dateien). Zaehlte das mit, bestuende die Dateiliste einer Runde aus fremden
Dateien und der Build-Hash haenge daran, welche Paketversion npm aufgeloest hat.
"""
import os
import sys

sys.path.insert(0, os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
import run_game_bench as r

sys.path.insert(0, os.path.join(os.path.dirname(os.path.dirname(os.path.abspath(__file__))), "tools"))
import collect_builds as cb


def _build(tmp_path):
    tmp_path.mkdir(parents=True, exist_ok=True)
    (tmp_path / "index.html").write_text("<!doctype html><script src=game.js></script>")
    (tmp_path / "game.js").write_text("console.log(1)")
    nm = tmp_path / "node_modules" / "jsdom" / "lib"
    nm.mkdir(parents=True)
    (nm / "index.js").write_text("module.exports = {}")
    (tmp_path / "node_modules" / "package.json").write_text("{}")
    return tmp_path


def test_build_files_ignores_node_modules(tmp_path):
    files = r.build_files(str(_build(tmp_path)))
    assert files == ["game.js", "index.html"]


def test_build_hash_is_blind_to_an_install(tmp_path):
    """Eine Runde, die nur ein Paket nachinstalliert, ist KEINE geaenderte Runde."""
    w = _build(tmp_path)
    before = r.build_hash(str(w))
    extra = w / "node_modules" / "left-pad"
    extra.mkdir()
    (extra / "index.js").write_text("module.exports = () => {}")
    assert r.build_hash(str(w)) == before
    # ...eine Runde, die den Build aendert, dagegen schon.
    (w / "game.js").write_text("console.log(2)")
    assert r.build_hash(str(w)) != before


def test_copy_round_leaves_node_modules_behind(tmp_path):
    src = _build(tmp_path / "src")
    dst = tmp_path / "dst"
    cb.copy_round(str(src), str(dst))
    assert (dst / "index.html").exists()
    assert (dst / "game.js").exists()
    assert not (dst / "node_modules").exists()


def test_copy_round_still_takes_real_subdirectories(tmp_path):
    """Die Ausnahme gilt node_modules, nicht Unterverzeichnissen allgemein --
    grade-*/ traegt die Screenshots, js/ traegt den Build."""
    src = tmp_path / "src"
    (src / "js").mkdir(parents=True)
    (src / "index.html").write_text("x")
    (src / "js" / "core.js").write_text("y")
    (src / "grade-0").mkdir()
    (src / "grade-0" / "title.png").write_bytes(b"\x89PNG")
    dst = tmp_path / "dst"
    cb.copy_round(str(src), str(dst))
    assert (dst / "js" / "core.js").exists()
    assert (dst / "grade-0" / "title.png").exists()
